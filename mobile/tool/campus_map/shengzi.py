"""Generates app-content/campus-map/shengzi.json (生資大樓).

Eight floors (the building's upper four are not signed), each read off a
photo of a sign and fitted to the OpenStreetMap outline by the outer
corners of its two wings, which also takes out the camera's slant. The
building is an H lying on its side: a north and a south wing, 74 m long,
joined in the middle by the lecture-hall block, with stair towers at the
wings' ends. Most signs put east up, so the north wing is on the left;
8F's emergency map (and 7F's, used only for names) is turned the other
way, west up.

1F and 2F come from the coloured floor plans with their directories; 3F
and 4F from the blue emergency maps; 5F and 7F from the departments'
coloured plans, 6F from the 1/200 plan beside its directory, 8F from the
emergency map. Where the sign and directory disagree the room's own floor
sign wins, and the directory's other number goes in `aka` (8F's 817D is
the directory's 817-4).

No building character shows on any sign, so rooms carry no `code`: like
the library, the number leads the name (101 教學互動多功能室).
"""
import json
from pathlib import Path

# The OpenStreetMap outline's four outer corners, metres east and south of
# its bounding box's north-west corner.
NE, NW, SW, SE = (74.1, 0), (0, 1.4), (0.6, 60.2), (74.4, 58.9)


def solve(a, b):
    """Gaussian elimination for a small dense system."""
    n = len(b)
    m = [row[:] + [v] for row, v in zip(a, b)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(m[r][c]))
        m[c], m[p] = m[p], m[c]
        for r in range(n):
            if r != c:
                f = m[r][c] / m[c][c]
                m[r] = [x - f * y for x, y in zip(m[r], m[c])]
    return [m[r][n] / m[r][r] for r in range(n)]


class Sign:
    """One photographed plan, east up and north on the left, fitted by the
    outer corners of its two wings: the north wing's top-left and
    bottom-left, the south wing's bottom-right and top-right (pixels in a
    1600-px-long-side copy of the photo)."""

    def __init__(self, tl, bl, br, tr, west_up=False):
        a, b = [], []
        corners = (SW, SE, NE, NW) if west_up else (NE, NW, SW, SE)
        for (u, v), (x, y) in zip((tl, bl, br, tr), corners):
            a.append([u, v, 1, 0, 0, 0, -u * x, -v * x])
            b.append(x)
            a.append([0, 0, 0, u, v, 1, -u * y, -v * y])
            b.append(y)
        self.h = solve(a, b)

    def pt(self, u, v):
        h = self.h
        w = h[6] * u + h[7] * v + 1
        return [round((h[0] * u + h[1] * v + h[2]) / w, 2), round((h[3] * u + h[4] * v + h[5]) / w, 2)]

    def pts(self, ps):
        return [self.pt(*p) for p in ps]

    def rect(self, kind, u0, v0, u1, v1, name=None, note=None, aka=None):
        """A box on the sign: a rectangle in metres unless the photo's slant
        skews it noticeably."""
        ps = self.pts([(u0, v0), (u1, v0), (u1, v1), (u0, v1)])
        xs, ys = [p[0] for p in ps], [p[1] for p in ps]
        area = abs(sum(p[0] * q[1] - q[0] * p[1] for p, q in zip(ps, ps[1:] + ps[:1]))) / 2
        x0, y0 = min(xs), min(ys)
        if area > .96 * (max(xs) - x0) * (max(ys) - y0):
            space = {"kind": kind, "rect": [x0, y0, round(max(xs) - x0, 2), round(max(ys) - y0, 2)]}
        else:
            space = {"kind": kind, "polygon": ps}
        return labelled(space, name, note, aka)

    def poly(self, kind, ps, name=None, note=None):
        return labelled({"kind": kind, "polygon": self.pts(ps)}, name, note, None)

    def room(self, u0, v0, u1, v1, num=None, name=None, note=None, aka=None):
        """A numbered room, named as the signs name it ("101 教學互動多功能室")."""
        label = " ".join(x for x in (num, name) if x) or None
        return self.rect("room", u0, v0, u1, v1, label, note, aka)

    def stack(self, u0, u1, edges, rooms):
        """Rooms stacked down the sign between edges (east to west)."""
        assert len(edges) == len(rooms) + 1, (edges, rooms)
        out = []
        for (a, b), r in zip(zip(edges, edges[1:]), rooms):
            if r is None:
                continue
            if isinstance(r, str):
                r = (r,)
            num, *rest = r
            name = rest[0] if rest else None
            aka = rest[1] if len(rest) > 1 else None
            out.append(self.room(u0, a, u1, b, num, name, aka=aka))
        return out


def h_outline(g, left, right, mid, ts):
    """The H on a sign: the two wings (x0, x1, y0, y1 in pixels), the
    middle block's top and bottom, and the four stair towers beyond the
    wings' ends (x0, x1, outer y, wing y), top-left, top-right, bottom-right,
    bottom-left."""
    lx0, lx1, ly0, ly1 = left
    rx0, rx1, ry0, ry1 = right
    my0, my1 = mid
    (a0, a1, at, _), (b0, b1, bt, _), (c0, c1, cb, _), (d0, d1, db, _) = ts
    return g.pts([(lx0, ly0), (a0, ly0), (a0, at), (a1, at), (a1, ly0), (lx1, ly0), (lx1, my0), (rx0, my0),
                  (rx0, ry0), (b0, ry0), (b0, bt), (b1, bt), (b1, ry0), (rx1, ry0), (rx1, ry1), (c1, ry1),
                  (c1, cb), (c0, cb), (c0, ry1), (rx0, ry1), (rx0, my1), (lx1, my1), (lx1, ly1), (d1, ly1),
                  (d1, db), (d0, db), (d0, ly1), (lx0, ly1)])


def towers(g, ts):
    """The four stair towers as stairs, from their (x0, x1, outer y, wing y)."""
    return [g.rect("stairs", min(x0, x1), min(y, w), max(x0, x1), max(y, w)) for x0, x1, y, w in ts]


def labelled(space, name, note, aka):
    if name:
        space["name"] = name
    if aka:
        space["aka"] = aka
    if note:
        space["note"] = note
    return space


